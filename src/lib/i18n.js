export function getLang() {
  try {
    const saved = localStorage.getItem(LS_LANG_KEY);
    if (saved && dict[saved]) return saved;
  } catch {}
  return "it";
}

// For guest pages (trip share links) — no household session, so no persisted
// language pref to read. Fall back to the browser's own language instead.
export function detectGuestLang() {
  try {
    const codes = [navigator.language, ...(navigator.languages || [])];
    for (const c of codes) {
      const short = (c || "").slice(0, 2).toLowerCase();
      if (dict[short]) return short;
    }
  } catch {}
  return "it";
}

export function setLang(lang) {
  try { localStorage.setItem(LS_LANG_KEY, dict[lang] ? lang : "it"); } catch {}
}

export function t(lang, key) {
  return dict[lang]?.[key] ?? dict.it[key] ?? key;
}

const MESI = {
  it: ["Gen", "Feb", "Mar", "Apr", "Mag", "Giu", "Lug", "Ago", "Set", "Ott", "Nov", "Dic"],
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
};

// Month abbreviation by index (0-11). `lang` defaults to the persisted
// language so call sites that haven't threaded a `lang` prop through yet
// still render correctly.
export function mese(i, lang = getLang()) {
  return (MESI[lang] || MESI.it)[i];
}
